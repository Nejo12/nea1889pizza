// Generates the vendored copy of the booking engine inside the Lovable-connected repository.
// This repository stays the ONLY place where reservation rules, the pg adapter and guest handlers are edited;
// the copy is mechanical (header + 3 import rewrites) and verified, never hand-edited.
//   node scripts/sync-lovable.mjs --target <lovable-checkout>            write the copy
//   node scripts/sync-lovable.mjs --target <lovable-checkout> --check    exit 1 if the copy is missing/stale/edited
import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const OUT_DIR='src/server/booking';
// source (this repo) -> file name inside OUT_DIR
export const FILES=[['lib/database.ts','database.ts'],['lib/reservation-rules.ts','reservation-rules.ts'],['lib/booking-store.ts','booking-store.ts'],['app/api/booking/route.ts','guest-api.ts']];
const sha=s=>createHash('sha256').update(s).digest('hex');
const HEADER=/^\/\/ GENERATED[^\n]*\n\/\/ source-sha256: ([0-9a-f]{64}) output-sha256: ([0-9a-f]{64})\n/;
// Only these import shapes are understood; anything else fails loudly instead of being copied blindly.
export function rewrite(source,name){
 const staleNames=new Set(FILES.map(f=>f[1].replace(/\.ts$/,'')));
 return source.replace(/^(import\s+(?:type\s+)?(?:\{([^}]*)\}|[\w*\s,{}]+?)\s+from\s+)'([^']+)'/gm,(all,pre,names,spec)=>{
  if(spec==='zod')return `${pre}'zod/v4'`; // Lovable pins zod 3.25.x, which ships the v4 API at zod/v4
  if(spec==='postgres'||spec==='./reservation-rules'||spec==='./database')return all;
  if(spec==='./staff'||spec==='@/lib/staff'){
   const used=(names||'').split(',').map(s=>s.trim()).filter(Boolean);
   if(used.length!==1||used[0]!=='database')throw Error(`${name}: only "database" may be imported from staff (got ${used.join(',')}); Clerk/auth must not enter the vendored engine.`);
   return `${pre}'./database'`;
  }
  const m=spec.match(/^@\/lib\/([\w-]+)$/);
  if(m&&staleNames.has(m[1]))return `${pre}'./${m[1]}'`;
  throw Error(`${name}: unsupported import '${spec}'`);
 });
}
export function generate(repoRoot=root){
 return FILES.map(([src,out])=>{
  const source=readFileSync(path.join(repoRoot,src),'utf8'),body=rewrite(source,src);
  const header=`// GENERATED by scripts/sync-lovable.mjs from Nejo12/nea1889pizza:${src} — DO NOT EDIT. Change the source repository and re-sync.\n// source-sha256: ${sha(source)} output-sha256: ${sha(body)}\n`;
  return {file:out,content:header+body};
 });
}
export function verify(targetDir,repoRoot=root){
 const problems=[];
 for(const {file,content} of generate(repoRoot)){
  const p=path.join(targetDir,OUT_DIR,file);
  if(!existsSync(p)){problems.push(`${file}: missing`);continue;}
  const actual=readFileSync(p,'utf8'),h=actual.match(HEADER);
  if(!h||sha(actual.slice(h[0].length))!==h[2])problems.push(`${file}: edited by hand (output hash mismatch)`);
  else if(actual!==content)problems.push(`${file}: stale (source changed; re-run sync)`);
 }
 return problems;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const t=process.argv.indexOf('--target'),target=t>0&&process.argv[t+1];
 if(!target){console.error('usage: sync-lovable.mjs --target <lovable-checkout> [--check]');process.exit(2);}
 if(process.argv.includes('--check')){const p=verify(target);if(p.length){console.error(p.join('\n'));process.exit(1);}console.log('vendored booking engine is in sync');}
 else{mkdirSync(path.join(target,OUT_DIR),{recursive:true});for(const f of generate())writeFileSync(path.join(target,OUT_DIR,f.file),f.content);console.log('wrote '+FILES.length+' files to '+path.join(target,OUT_DIR));}
}
